-- Aawaaz V2 schema: users (manager + workers), categories, requests.
-- Run by Spring Boot SQL init on every startup (in-memory H2 resets each run).
-- DROP first so re-runs within the same JVM are idempotent.

DROP TABLE IF EXISTS requests;
DROP TABLE IF EXISTS categories;
DROP TABLE IF EXISTS users;

-- ---------------------------------------------------------------------------
-- users: one table for both managers and workers.
--   user_type     = MANAGER | WORKER
--   profession    = worker's trade/role (nullable; null for managers)
--   language_code = preferred language (worker speaks it; manager reads in it)
-- ---------------------------------------------------------------------------
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL UNIQUE,
    name          VARCHAR(128) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,              -- BCrypt hash, never plaintext
    user_type     VARCHAR(16)  NOT NULL,
    profession    VARCHAR(64),
    language_code VARCHAR(8)   NOT NULL DEFAULT 'en-IN',
    face_embedding CLOB,                                 -- CSV of floats; null = no face enrolled
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_user_type CHECK (user_type IN ('MANAGER', 'WORKER'))
);

-- ---------------------------------------------------------------------------
-- categories: same set the mobile app seeds. Static — no add/remove; only
-- priority is mutable (higher sorts first). Safety and health are safety-critical.
-- ---------------------------------------------------------------------------
CREATE TABLE categories (
    category_key       VARCHAR(32) PRIMARY KEY,
    label              VARCHAR(64) NOT NULL,
    priority           INT         NOT NULL DEFAULT 0,
    is_safety_critical BOOLEAN     NOT NULL DEFAULT FALSE
);

-- ---------------------------------------------------------------------------
-- requests: what a worker says, stored verbatim, plus translations (filled by
-- the service via Sarvam).
--   original_text     = exact phrase in the worker's language (never altered)
--   original_language = e.g. hi-IN / bn-IN / en-IN
--   translated_text   = request translated to ENGLISH (canonical; dashboard shows this)
--   manager_comment   = the manager's reply, in the manager's language
--   manager_comment_translated = that reply translated to the WORKER's language (playback)
-- ---------------------------------------------------------------------------
CREATE TABLE requests (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    worker_id                BIGINT        NOT NULL,
    original_text            VARCHAR(1000) NOT NULL,
    original_language        VARCHAR(8)    NOT NULL,
    translated_text          VARCHAR(1000),
    translated_language      VARCHAR(8),
    category_key             VARCHAR(32)   NOT NULL DEFAULT 'other',
    urgency                  VARCHAR(16)   NOT NULL DEFAULT 'NORMAL',
    status                   VARCHAR(16)   NOT NULL DEFAULT 'OPEN',
    manager_comment          VARCHAR(1000),
    manager_comment_language VARCHAR(8),
    manager_comment_translated          VARCHAR(1000),
    manager_comment_translated_language VARCHAR(8),
    commented_at             TIMESTAMP,
    created_at               TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at               TIMESTAMP,
    CONSTRAINT fk_requests_worker   FOREIGN KEY (worker_id)    REFERENCES users (id),
    CONSTRAINT fk_requests_category FOREIGN KEY (category_key) REFERENCES categories (category_key),
    CONSTRAINT chk_urgency CHECK (urgency IN ('HIGH', 'NORMAL', 'LOW')),
    CONSTRAINT chk_status  CHECK (status  IN ('OPEN', 'IN_PROGRESS', 'RESOLVED'))
);

CREATE INDEX idx_requests_worker   ON requests (worker_id);
CREATE INDEX idx_requests_status   ON requests (status);
CREATE INDEX idx_requests_category ON requests (category_key);
